class NadwiLanguage {
  constructor() {
    this.LANG_KEY = "NADWI_APP_LANG";
    this.currentLang = localStorage.getItem(this.LANG_KEY) || "en";
    this.init();
  }

  init() {
    this.applyLanguage(this.currentLang);
  }

  applyLanguage(lang) {
    this.currentLang = lang;
    localStorage.setItem(this.LANG_KEY, lang);

    const isRtl = (lang === "ur");
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl ? "rtl" : "ltr";

    if (isRtl) {
      document.body.classList.add("rtl");
      document.body.classList.add("lang-ur");
    } else {
      document.body.classList.remove("rtl");
      document.body.classList.remove("lang-ur");
    }

    // Update all elements with [data-i18n]
    const elements = document.querySelectorAll("[data-i18n]");
    const dict = NADWI_TRANSLATIONS[lang] || NADWI_TRANSLATIONS.en;

    elements.forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        if (el.tagName === "INPUT" && el.hasAttribute("placeholder")) {
          el.placeholder = dict[key];
        } else {
          el.textContent = dict[key];
        }
      }
    });

    // Update language switch button text if present
    const langBtnText = document.getElementById("langBtnText");
    if (langBtnText) {
      langBtnText.textContent = isRtl ? "English" : "اردو";
    }
  }

  toggle() {
    const nextLang = this.currentLang === "en" ? "ur" : "en";
    this.applyLanguage(nextLang);
  }

  t(key) {
    const dict = NADWI_TRANSLATIONS[this.currentLang] || NADWI_TRANSLATIONS.en;
    return dict[key] || key;
  }
}

// Global Singleton Instance
window.NadwiLang = new NadwiLanguage();

